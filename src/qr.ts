// QR code encoder (ISO/IEC 18004), byte mode, versions 1–40, error correction L/M/Q/H.
// Written for Honeyguide so labels work offline with no third-party library.
// Follows the reference construction popularised by Project Nayuki (MIT).

export type Ecc = 'L' | 'M' | 'Q' | 'H';
const ECC_INDEX: Record<Ecc, number> = { L: 0, M: 1, Q: 2, H: 3 };
const FORMAT_BITS: Record<Ecc, number> = { L: 1, M: 0, Q: 3, H: 2 };

